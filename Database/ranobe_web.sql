    admin_user_id INT;
BEGIN
    SELECT a.user_id INTO admin_user_id
    FROM accounts a
    WHERE a.username = 'admin';

    IF admin_user_id IS NULL THEN
        INSERT INTO users (user_name, birth, is_deleted)
        VALUES ('Admin', CURRENT_DATE, FALSE)
        RETURNING user_id INTO admin_user_id;

        INSERT INTO accounts (user_id, email, username, password, role, is_deleted)
        VALUES (admin_user_id, 'admin@ranobe.local', 'admin', 'admin123', 'ADMIN', FALSE);
    ELSE
        UPDATE accounts
        SET role = 'ADMIN', is_deleted = FALSE
        WHERE username = 'admin';
    END IF;
END $$;

