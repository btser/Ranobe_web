CREATE TABLE IF NOT EXISTS chapter_images (
    image_id INT GENERATED BY DEFAULT AS IDENTITY,
    chapter_id INT NOT NULL,
    image_url TEXT NOT NULL,
    sort_order INT DEFAULT 0,
    CONSTRAINT PK_chapter_images PRIMARY KEY (image_id),
    CONSTRAINT FK_chapter_images_chapters FOREIGN KEY (chapter_id) REFERENCES chapters(chapter_id) ON DELETE CASCADE
);

