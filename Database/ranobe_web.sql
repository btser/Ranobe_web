-- 1. Tạo các kiểu ENUM trước
CREATE TYPE product_status AS ENUM ('PUBLIC', 'PRIVATE');
CREATE TYPE ranking_sort_by AS ENUM ('View', 'Comment', 'Vote', 'Word', 'All');

-- 2. Tạo bảng categories (Không phụ thuộc vào bảng nào)
CREATE TABLE categories (
    category_id INT GENERATED BY DEFAULT AS IDENTITY,
    category_name VARCHAR(100) NOT NULL,
    CONSTRAINT PK_categories PRIMARY KEY (category_id)
);

-- 3. Tạo bảng users (Không phụ thuộc vào bảng nào)
CREATE TABLE users (
    user_id INT GENERATED BY DEFAULT AS IDENTITY,
    user_name VARCHAR(100) NOT NULL,
    avatar_url TEXT,
    birth DATE,
    hobby TEXT,
    introduce TEXT,
    CONSTRAINT PK_users PRIMARY KEY (user_id)
);

-- 4. Tạo bảng accounts (Phụ thuộc vào users)
CREATE TABLE accounts (
    account_id INT GENERATED BY DEFAULT AS IDENTITY,
    user_id INT NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    username VARCHAR(50) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL, -- Độ dài 255 để sau này lưu hash password (BCrypt/Argon2)
    CONSTRAINT PK_accounts PRIMARY KEY (account_id),
    CONSTRAINT FK_accounts_users FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE CASCADE
);

-- 5. Tạo bảng products (Phụ thuộc vào users và categories)
CREATE TABLE products (
    product_id INT GENERATED BY DEFAULT AS IDENTITY,
    user_id INT NOT NULL,
    title VARCHAR(255) NOT NULL,
    category_id INT NOT NULL,
    author VARCHAR(150),
    artist VARCHAR(150),
    status product_status DEFAULT 'PRIVATE',
    CONSTRAINT PK_products PRIMARY KEY (product_id),
    CONSTRAINT FK_products_users FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE RESTRICT,
    CONSTRAINT FK_products_categories FOREIGN KEY (category_id) REFERENCES categories(category_id) ON DELETE RESTRICT
);

-- 6. Tạo bảng ranking (Mối quan hệ 1-1 hoặc 1-N với products, dựa trên ERD của bạn là 1-1 hoặc N-1 phụ thuộc vào product_id làm PK)
CREATE TABLE ranking (
    product_id INT NOT NULL,
    sort_by ranking_sort_by NOT NULL,
    total_points REAL DEFAULT 0.0, -- float trong Postgres map thành REAL hoặc DOUBLE PRECISION
    total_cmts INT DEFAULT 0,
    total_views INT DEFAULT 0,
    avg_vote REAL DEFAULT 0.0,
    total_words INT DEFAULT 0,
    CONSTRAINT PK_ranking PRIMARY KEY (product_id),
    CONSTRAINT FK_ranking_products FOREIGN KEY (product_id) REFERENCES products(product_id) ON DELETE CASCADE
);

-- 7. Tạo bảng volumes (Phụ thuộc vào products)
CREATE TABLE volumes (
    volume_id INT GENERATED BY DEFAULT AS IDENTITY,
    product_id INT NOT NULL,
    CONSTRAINT PK_volumes PRIMARY KEY (volume_id),
    CONSTRAINT FK_volumes_products FOREIGN KEY (product_id) REFERENCES products(product_id) ON DELETE CASCADE
);

-- 8. Tạo bảng chapters (Phụ thuộc vào volumes)
CREATE TABLE chapters (
    chapter_id INT GENERATED BY DEFAULT AS IDENTITY,
    volume_id INT NOT NULL,
    context TEXT, -- Nội dung chương truyện/sách lưu dạng TEXT thoải mái dung lượng
    CONSTRAINT PK_chapters PRIMARY KEY (chapter_id),
    CONSTRAINT FK_chapters_volumes FOREIGN KEY (volume_id) REFERENCES volumes(volume_id) ON DELETE CASCADE
);