-- Không chứa dữ liệu người dùng hoặc mật khẩu. IF NOT EXISTS tiếp nhận cả cơ sở dữ liệu đang có.
CREATE TABLE IF NOT EXISTS categories (
    category_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR(255), is_deleted BOOLEAN DEFAULT FALSE
);
CREATE TABLE IF NOT EXISTS users (
    user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_name VARCHAR(100), avatar_url VARCHAR(255), birth DATE,
    hobby TEXT, introduce TEXT, cover_url TEXT, is_deleted BOOLEAN DEFAULT FALSE
);
CREATE TABLE IF NOT EXISTS accounts (
    account_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER REFERENCES users(user_id), email VARCHAR(255), username VARCHAR(255),
    password VARCHAR(255), role VARCHAR(255) DEFAULT 'USER', is_deleted BOOLEAN DEFAULT FALSE
);
CREATE TABLE IF NOT EXISTS products (
    product_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER REFERENCES users(user_id), category_id INTEGER REFERENCES categories(category_id),
    title VARCHAR(255), author VARCHAR(255), artist VARCHAR(255), status VARCHAR(255) DEFAULT 'PRIVATE',
    cover_image TEXT, summary TEXT, updated_at TIMESTAMP, is_deleted BOOLEAN DEFAULT FALSE
);
CREATE TABLE IF NOT EXISTS volumes (
    volume_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id INTEGER REFERENCES products(product_id), title VARCHAR(255), cover_image TEXT, summary TEXT,
    sort_order INTEGER DEFAULT 0, is_deleted BOOLEAN DEFAULT FALSE
);
CREATE TABLE IF NOT EXISTS chapters (
    chapter_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    volume_id INTEGER REFERENCES volumes(volume_id), title VARCHAR(255), context TEXT,
    sort_order INTEGER DEFAULT 0, is_deleted BOOLEAN DEFAULT FALSE, is_completed BOOLEAN DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS chapter_images (
    image_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chapter_id INTEGER REFERENCES chapters(chapter_id), image_url TEXT, sort_order INTEGER DEFAULT 0
);
CREATE TABLE IF NOT EXISTS product_categories (
    product_id INTEGER NOT NULL REFERENCES products(product_id),
    category_id INTEGER NOT NULL REFERENCES categories(category_id), PRIMARY KEY(product_id,category_id)
);
CREATE TABLE IF NOT EXISTS ranking (
    product_id INTEGER PRIMARY KEY REFERENCES products(product_id), sort_by VARCHAR(255) DEFAULT 'All',
    total_points REAL DEFAULT 0, total_cmts INTEGER DEFAULT 0, total_views INTEGER DEFAULT 0,
    avg_vote REAL DEFAULT 0, total_words INTEGER DEFAULT 0
);
CREATE TABLE IF NOT EXISTS image_cleanup_candidates (
    object_key VARCHAR(255) PRIMARY KEY, object_etag VARCHAR(255) NOT NULL,
    object_modified_at TIMESTAMP WITH TIME ZONE NOT NULL,
    unreferenced_since TIMESTAMP WITH TIME ZONE NOT NULL, retry_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX IF NOT EXISTS idx_image_cleanup_due ON image_cleanup_candidates(unreferenced_since);
CREATE TABLE IF NOT EXISTS image_cleanup_state (
    id INTEGER PRIMARY KEY, prefix_index INTEGER NOT NULL,
    continuation_token TEXT, next_scan_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE IF NOT EXISTS pdf_import_receipts (
    token VARCHAR(36) PRIMARY KEY, user_id INTEGER NOT NULL, volume_id INTEGER NOT NULL,
    completed_at TIMESTAMP WITH TIME ZONE NOT NULL
);
