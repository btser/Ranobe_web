CREATE TABLE product_views (
    product_id INTEGER NOT NULL REFERENCES products(product_id) ON DELETE CASCADE,
    viewer_key VARCHAR(36) NOT NULL, view_bucket BIGINT NOT NULL,
    viewed_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY(product_id,viewer_key,view_bucket)
);
CREATE INDEX idx_product_views_time ON product_views(product_id,viewed_at);
CREATE TABLE product_votes (
    product_id INTEGER NOT NULL REFERENCES products(product_id) ON DELETE CASCADE,
    user_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY(product_id,user_id)
);
CREATE INDEX idx_product_votes_time ON product_votes(product_id,created_at);
CREATE TABLE product_comments (
    comment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id INTEGER NOT NULL REFERENCES products(product_id) ON DELETE CASCADE,
    user_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    body VARCHAR(2000) NOT NULL CHECK (LENGTH(TRIM(body))>0),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_product_comments_time ON product_comments(product_id,created_at,comment_id);
CREATE INDEX idx_product_comments_user_time ON product_comments(user_id,created_at);
