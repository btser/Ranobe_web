CREATE TABLE discuss (
    discuss_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(user_id),
    title VARCHAR(200) NOT NULL CHECK (LENGTH(TRIM(title))>0),
    content VARCHAR(20000) NOT NULL CHECK (LENGTH(TRIM(content))>0),
    notification BOOLEAN NOT NULL DEFAULT FALSE,
    views BIGINT NOT NULL DEFAULT 0 CHECK (views>=0),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_updated TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    is_locked BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_discuss_created ON discuss(created_at DESC,discuss_id DESC);
CREATE INDEX idx_discuss_author ON discuss(user_id,created_at DESC);
CREATE TABLE comments (
    comment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    discuss_id BIGINT NOT NULL REFERENCES discuss(discuss_id),
    user_id INTEGER NOT NULL REFERENCES users(user_id),
    content VARCHAR(5000) NOT NULL CHECK (LENGTH(TRIM(content))>0),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_updated TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_comments_topic_time ON comments(discuss_id,created_at DESC,comment_id DESC);
CREATE INDEX idx_comments_author_time ON comments(user_id,created_at DESC);
